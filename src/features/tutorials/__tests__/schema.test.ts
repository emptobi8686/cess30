import assert from "node:assert/strict";
import { test } from "node:test";
import { tutorialSchema } from "../schema";

const base = {
  title: "Shear force diagrams",
  description: "Worked example.",
  topic: "Beams",
  learning_objectives: "Draw an SFD\nFind maximum shear",
  video_url: "https://www.youtube.com/watch?v=dQw4w9WgXcQ",
  is_ai_generated: undefined as string | undefined,
  ai_tool: "",
  ai_disclosure: "",
  duration_minutes: "",
  course_id: "",
  level_code: "200",
};

test("a YouTube tutorial parses and keeps one objective per line", () => {
  const r = tutorialSchema.safeParse(base);
  assert.equal(r.success, true);
  assert.deepEqual(r.success && r.data.learning_objectives, ["Draw an SFD", "Find maximum shear"]);
  assert.deepEqual(r.success && r.data.video, { provider: "youtube", id: "dQw4w9WgXcQ" });
});

test("AI tutorials need a tool and a disclosure", () => {
  assert.equal(tutorialSchema.safeParse({ ...base, is_ai_generated: "on" }).success, false);
  assert.equal(tutorialSchema.safeParse({ ...base, is_ai_generated: "on", ai_tool: "Video generator", ai_disclosure: "Narration generated by AI." }).success, true);
});

test("at most 8 learning objectives, each 5-200 characters", () => {
  const nine = Array.from({ length: 9 }, (_, i) => `Objective number ${i}`).join("\n");
  assert.equal(tutorialSchema.safeParse({ ...base, learning_objectives: nine }).success, false);
  assert.equal(tutorialSchema.safeParse({ ...base, learning_objectives: "abc" }).success, false);
});

test("non-allow-listed or look-alike URLs are rejected", () => {
  assert.equal(tutorialSchema.safeParse({ ...base, video_url: "https://youtube.com.evil.example/watch?v=dQw4w9WgXcQ" }).success, false);
  assert.equal(tutorialSchema.safeParse({ ...base, video_url: "https://example.org/video" }).success, false);
});

test("duration is entered in minutes and stored in seconds", () => {
  const r = tutorialSchema.safeParse({ ...base, duration_minutes: "12" });
  assert.equal(r.success && r.data.duration_seconds, 720);
});
